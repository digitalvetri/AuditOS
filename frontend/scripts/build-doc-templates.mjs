/**
 * The execution page: 'Signed and delivered by', the two designated partners
 * side by side with a space to sign, and the two witnesses. Word wrote this
 * as tab-separated runs inside single paragraphs, which is not a structure —
 * so it is rebuilt here as the signature and witness blocks the editor knows,
 * each field separately editable and each signature separately uploadable.
 */
function executionTail() {
  return [
    { key: 'paragraph', lines: [{ kind: 'p', align: 'left', indent: 0, html: '<b>Signed and delivered by:</b>' }] },
    { key: 'signature', columns: 2, people: [
      { name: '{{partner1_name}}', role: '(Designated Partner) ({{partner1_din}})', din: '', note: '' },
      { name: '{{partner2_name}}', role: '(Designated Partner) ({{partner2_din}})', din: '', note: '' },
    ] },
    { key: 'witness', people: [
      { name: '', role: '', din: 'a)', note: 'Witness:' },
      { name: '', role: '', din: 'b)', note: 'Witness:' },
    ] },
  ];
}

/**
 * A place to sign under a numbered clause. The clause lives inside a
 * paragraph with its neighbours, so the paragraph is SPLIT after that line
 * and the signature block goes between the halves — which is what puts the
 * two slots directly under the clause rather than at the end of the group.
 */
function signAfterClause(out, n) {
  const re = new RegExp(`^${n}\\.\\s`);
  for (let i = 0; i < out.length; i++) {
    const lines = out[i].lines ?? [];
    const at = lines.findIndex((l) => re.test(l.html));
    if (at === -1) continue;
    const head = { ...out[i], lines: lines.slice(0, at + 1) };
    const tail = lines.slice(at + 1);
    // Spaces to sign, nothing else: the partners are named in the clause and
    // again on the execution page, so printing them here twice reads wrong.
    const sign = { key: 'signature', variant: 'upload', columns: 2, people: [
      { name: '', role: '', din: '', note: '' },
      { name: '', role: '', din: '', note: '' },
    ] };
    const rest = tail.length ? [{ ...out[i], lines: tail }] : [];
    return [...out.slice(0, i), head, sign, ...rest, ...out.slice(i + 1)];
  }
  return out;
}

/** Everything from 'Signed and delivered by' on is replaced by that tail. */
function withExecutionTail(out) {
  const at = out.findIndex((b) => (b.lines ?? []).some((l) => /Signed and\s*delivered by/i.test(l.html)));
  if (at === -1) return out;
  const keep = out.slice(0, at);
  const block = out[at];
  // The paragraph may hold clauses BEFORE the sign-off; those stay.
  const before = (block.lines ?? []).filter((l) => !/Signed and\s*delivered by|Designated Partner\)|^Witness:|^[ab]\) Name:|^Address:|^Signature:|^\{\{partner\d_name\}\}/i.test(l.html));
  if (before.length) keep.push({ ...block, lines: before });
  return [...keep, ...executionTail()];
}

