/**
 * Build the two LONG agreement templates from their reference .docx.
 *
 * The eleven letters and resolutions are written out by hand in
 * src/modules/workstation/docs/templates/ — they are short, and their
 * placeholders are chosen clause by clause. The LLP agreement and the
 * partnership deed are forty-odd clauses each: transcribing those by hand is
 * how a word goes missing from a legal document, so they are EXTRACTED from
 * the reference file and emitted as a template, with the reference firm's own
 * particulars swapped for placeholders.
 *
 *   node scripts/build-doc-templates.mjs "/path/to/Documents-set"
 *
 * Re-run it when a reference document changes; the output is committed.
 */
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';

const SRC = process.argv[2] ?? '/home/kaarthika/Desktop/Audit OS/Documents-set';
const OUT = path.resolve('src/modules/workstation/docs/templates');

const ALIGN = { both: 'justify', center: 'center', right: 'right', left: 'left' };

/** The .docx paragraphs: text, alignment, boldness and list-ness. */
function paragraphs(file) {
  const xml = execSync(`unzip -p ${JSON.stringify(path.join(SRC, file))} word/document.xml`, { maxBuffer: 1 << 28 }).toString();
  const out = [];
  for (const m of xml.matchAll(/<w:p\b[^>]*>([\s\S]*?)<\/w:p>/g)) {
    const p = m[1];
    // Runs IN ORDER, with <w:br/> kept as a line break: Word writes 'a) … b)
    // … c) …' and a signature block as ONE paragraph broken by <w:br/>, so
    // dropping the breaks is what ran those lines together.
    const text = [...p.matchAll(/<w:t[^>]*>([\s\S]*?)<\/w:t>|<w:br\b[^>]*>/g)]
      .map((x) => (x[1] === undefined ? '\n' : x[1]))
      .join('')
      .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
      .replace(/&quot;/g, '"').replace(/&apos;/g, "'")
      .replace(/[ \t]+/g, ' ')
      .split('\n').map((l) => l.trim()).filter(Boolean).join('\n')
      .trim();
    if (!text) continue;
    out.push({
      text,
      align: ALIGN[/<w:jc w:val="(\w+)"/.exec(p)?.[1]] ?? 'left',
      bold: /<w:b\s*\/>|<w:b /.test(p),
      list: /<w:numPr>/.test(p),
    });
  }
  return out;
}

const esc = (t) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/**
 * Word nests runs inside runs, and a naive <w:t> sweep can carry the markup
 * BETWEEN them into the text. Strip any tag that survived, and collapse the
 * tab runs it used for columns into a single space: columns are rebuilt as
 * real blocks below, not as runs of whitespace.
 */
const clean = (t) => t
  .replace(/<\/?w:[^>]*>/g, ' ')
  .replace(/[ \t]+/g, ' ')
  .trim();

/** A centred short bold line is a clause-group heading; '-3-' is a page number. */
const isHeading = (p) => p.align === 'center' && p.bold && p.text.length <= 70;
const isPageMark = (p) => /^-\s*\d+\s*-$/.test(p.text);

function blocks(paras, scrub) {
  const apply = (t) => scrub.reduce((s, [from, to, all]) => s.replace(all ? new RegExp(from.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g') : from, to), t);
  const out = [];
  let para = null;
  const flush = () => { if (para) { out.push(para); para = null; } };
  paras.forEach((p, i) => {
    if (isPageMark(p)) return;
    const text = apply(clean(p.text));
    if (isHeading(p)) {
      flush();
      out.push({ key: 'heading', title: text, variant: i === 0 ? 'title' : 'subtitle', align: 'center' });
      return;
    }
    // An ALL-CAPS numbered title — '5. CAPITAL CONTRIBUTION' — is a section.
    if (/^\d+\.\s+[A-Z][A-Z0-9 &,'()-]{3,}$/.test(text)) {
      flush();
      out.push({ key: 'heading', title: text, variant: 'subtitle', align: 'left' });
      return;
    }
    // One line per break — each is separately editable and prints on its own
    // line, which is what the reference document shows.
    if (!para) para = { key: 'paragraph', lines: [] };
    for (const part of text.split('\n')) {
      para.lines.push({
        kind: p.list ? 'bullet' : 'p',
        align: p.align === 'left' ? 'left' : p.align,
        indent: 0,
        html: p.bold && p.list ? `<b>${esc(part)}</b>` : esc(part),
      });
    }
  });
  flush();
  return out;
}

