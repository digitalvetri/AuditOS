for (const [file, name, scrub, note, out] of jobs) {
  let raw = withExecutionTail(blocks(paragraphs(file), scrub));
  // The LLP agreement is initialled under clause 17 as well as executed at
  // the end; the reference document leaves two spaces for it there.
  if (name === 'LLP_AGREEMENT_BLOCKS') raw = signAfterClause(raw, 17);
  writeFileSync(path.join(OUT, out), fmt(raw, name, note));
  console.log(`${out}: ${raw.length} blocks`);
}
